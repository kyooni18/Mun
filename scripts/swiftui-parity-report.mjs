#!/usr/bin/env node
// Generates docs/SWIFTUI_PARITY_REPORT.md from the parity manifest, the native
// lowering metadata and the SDK snapshot header. `--check` fails when the
// checked-in report is stale. Counts only: no coverage percentages.
import { readFileSync, writeFileSync, existsSync } from "node:fs"
import { resolve } from "node:path"
import * as Manifest from "../packages/core/dist/api-manifest.js"
import { nativeLoweringMetadata } from "../packages/compiler/dist/index.js"

const reportPath = resolve("docs/SWIFTUI_PARITY_REPORT.md")
const snapshotPath = resolve("api/swiftui-symbols.snapshot.json")
const manifest = Manifest.swiftUIApiManifest
const native = nativeLoweringMetadata()

// The first lines of the snapshot hold its provenance header.
const header = JSON.parse(`${readFileSync(snapshotPath, "utf8").split("\n  \"symbols\"")[0].replace(/,\s*$/, "")}}`)

const contractTerm = { exact: "source-contract parity", subset: "source-contract subset" }
const nativeTerm = { parity: "native semantic parity", divergent: "deliberate divergence" }
const webTerm = { parity: "web parity", approximation: "web approximation", unsupported: "web unsupported" }

const cell = text => String(text ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ")
const code = text => `\`${text}\``

function semantics(overload) {
  const nativeText = overload.native ? nativeTerm[overload.native] : "compatibility-only"
  return [contractTerm[overload.contract] ?? "—", nativeText, webTerm[overload.web] ?? "—"]
}

function notes(overload) {
  return [overload.subset, overload.divergence].filter(Boolean).join(" ")
}

const lines = []
const push = (...items) => lines.push(...items)

push(
  "# SwiftUI parity report",
  "",
  "Generated by `pnpm report:swiftui-parity` from the parity manifest (`@mun/core/swiftui-manifest`),",
  "the compiler's native lowering tables and the SDK snapshot. Do not edit by hand; `pnpm test:parity`",
  "fails when this file is stale. Terms are defined in [SWIFTUI_PARITY.md](SWIFTUI_PARITY.md).",
  "",
  `SDK: Xcode ${header.xcodeVersion} (${header.xcodeBuild}), ${header.sdk} ${header.sdkVersion} (${header.sdkBuild}), ${header.target}; modules ${header.modules.join(" + ")}.`,
  `Snapshot: ${header.symbolCount} reference symbols of ${header.extractedSymbolCount} public symbols (sha256 ${header.sha256.slice(0, 12)}…).`,
  "",
)

const viewOverloads = Object.values(manifest.views).flatMap(view => view.initializers)
const modifierOverloads = manifest.modifiers.flatMap(modifier => modifier.signatures)
const valueMembers = manifest.values.flatMap(value => value.members)
const count = (items, predicate) => items.filter(predicate).length
push(
  "## Summary",
  "",
  "| Surface | Native semantic parity | Deliberate divergence | Compatibility-only | Unsupported (listed) |",
  "| --- | --- | --- | --- | --- |",
  `| View initializers | ${count(viewOverloads, item => item.native === "parity")} | ${count(viewOverloads, item => item.native === "divergent")} | ${count(viewOverloads, item => !item.native)} | ${manifest.unsupported.views.length} Views |`,
  `| Modifier overloads | ${count(modifierOverloads, item => item.native === "parity")} | ${count(modifierOverloads, item => item.native === "divergent")} | ${count(modifierOverloads, item => !item.native)} | ${manifest.unsupported.modifiers.length} modifiers |`,
  `| Value members | ${count(valueMembers, item => item.native === "parity")} | ${count(valueMembers, item => item.native === "divergent")} | ${count(valueMembers, item => !item.native)} | — |`,
  "",
  `Native lowering implements ${native.views.length} View overloads, ${native.modifiers.length} modifier overloads and ${native.values.length} value members; \`pnpm check:swiftui-manifest\` proves these sets equal the native claims above.`,
  "",
)

push("## Views", "", "| View | Overload | Source contract | Native | Web | Notes |", "| --- | --- | --- | --- | --- | --- |")
for (const [name, view] of Object.entries(manifest.views)) {
  for (const overload of view.initializers) {
    push(`| ${name} | ${code(overload.signature)} | ${semantics(overload).join(" | ")} | ${cell(notes(overload))} |`)
  }
  if (view.initializers.length === 0 && view.compat) {
    push(`| ${name} | ${view.compat.initializers.map(item => code(item.signature)).join(", ")} | — | compatibility-only | — | Legacy graph only. |`)
  }
}
push("")

push("## Modifiers", "", "| Owner | Modifier | Source contract | Native | Web | Notes |", "| --- | --- | --- | --- | --- | --- |")
for (const modifier of manifest.modifiers.filter(item => item.signatures.some(signature => signature.native))) {
  for (const overload of modifier.signatures) {
    push(`| ${modifier.owner ?? "View"} | ${code(`.${overload.signature}`)} | ${semantics(overload).join(" | ")} | ${cell(notes(overload))} |`)
  }
}
push("")
const compatOnly = manifest.modifiers.filter(item => !item.signatures.some(signature => signature.native))
push(
  `Compatibility-only modifiers (legacy graph for \`.mun.ts\`, React, Vue and DOM; rejected by canonical \`.mun\`): ${compatOnly.map(item => code(`.${item.name}`)).join(", ")}.`,
  "",
)

push("## Values", "", "| Type | Member | Source contract | Native | Web | Notes |", "| --- | --- | --- | --- | --- | --- |")
for (const value of manifest.values) {
  for (const member of value.members) {
    push(`| ${value.name} | ${code(member.signature)} | ${semantics(member).join(" | ")} | ${cell(notes(member))} |`)
  }
}
push("")

push("## Mün extensions and compatibility spellings", "", "| Name | Signatures | Status | Reason | Canonical replacement |", "| --- | --- | --- | --- | --- |")
for (const extension of manifest.extensions) {
  push(`| ${extension.name} | ${extension.signatures.map(code).join(", ")} | ${extension.status === "extension" ? "Mün extension" : "compatibility-only"} | ${cell(extension.reason)} | ${cell(extension.replacement ?? "—")} |`)
}
push("")

push("## Deliberately unsupported", "", "| SwiftUI API | Reason |", "| --- | --- |")
for (const view of manifest.unsupported.views) push(`| ${view.name} | ${cell(view.reason)} |`)
for (const modifier of manifest.unsupported.modifiers) push(`| .${modifier.name} | ${cell(modifier.reason)} |`)
push("")
push("Unsupported overloads of supported APIs (each is diagnosed by name):", "")
for (const [owner, signatures] of Object.entries(manifest.unsupported.overloads)) {
  if (signatures.length) push(`- ${owner}: ${signatures.map(code).join(", ")}`)
}
push("")

push("## Global divergences", "")
for (const [name, text] of Object.entries(Manifest.swiftUIGlobalDivergences)) push(`- **${name}**: ${text}`)
push("")

const report = lines.join("\n")
if (process.argv.includes("--check")) {
  if (!existsSync(reportPath) || readFileSync(reportPath, "utf8") !== report) {
    console.error("docs/SWIFTUI_PARITY_REPORT.md is stale; run `pnpm report:swiftui-parity`.")
    process.exitCode = 1
  } else {
    console.log("SwiftUI parity report is current.")
  }
} else {
  writeFileSync(reportPath, report)
  console.log(`Wrote ${reportPath}`)
}
